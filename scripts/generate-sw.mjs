/**
 * Generate the service worker with a build-specific cache version.
 *
 * A hardcoded cache version meant an old `/offline` document could survive a
 * deployment and reference a CSS file that no longer exists. Every build now
 * writes a new version into both `public/sw.js` and `public/version.json`.
 * The client compares version.json with localStorage before registering.
 */
import { readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";

const root = process.cwd();
const templatePath = join(root, "scripts", "sw-template.js");
const outputPath = join(root, "public", "sw.js");
const versionPath = join(root, "public", "version.json");
const packagePath = join(root, "package.json");

const pkg = JSON.parse(await readFile(packagePath, "utf8"));
const builtAt = new Date().toISOString();
const stamp = builtAt.replace(/\D/g, "");
const version = `${pkg.version}-${stamp}`;

const template = await readFile(templatePath, "utf8");
if (!template.includes("__BUILD_VERSION__")) {
  throw new Error("sw-template.js is missing the __BUILD_VERSION__ token.");
}

const banner = `/* Generated by scripts/generate-sw.mjs. Do not edit directly. */\n`;
const worker = banner + template.replaceAll("__BUILD_VERSION__", version);
if (worker.includes("__BUILD_VERSION__")) {
  throw new Error("The service worker build version was not replaced.");
}

await Promise.all([
  writeFile(outputPath, worker, "utf8"),
  writeFile(versionPath, `${JSON.stringify({ version, builtAt }, null, 2)}\n`, "utf8"),
]);

console.log(`Generated service worker ${version}`);
